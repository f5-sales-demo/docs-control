import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import process from 'node:process';

const root = process.argv[2];
if (!root) throw new Error('repository root is required');

function extractScript(workflowPath, stepName) {
  const lines = fs.readFileSync(workflowPath, 'utf8').split('\n');
  const stepMarker = lines.indexOf(`      - name: ${stepName}`);
  if (stepMarker === -1) throw new Error(`step ${stepName} not found in ${workflowPath}`);
  const marker = lines.findIndex((line, index) => index > stepMarker && line === '          script: |');
  if (marker === -1) throw new Error(`github-script body not found for ${stepName}`);
  return lines
    .slice(marker + 1)
    .filter((line) => line === '' || line.startsWith('            '))
    .map((line) => (line === '' ? line : line.slice(12)))
    .join('\n');
}

const AsyncFunction = Object.getPrototypeOf(async () => {}).constructor;
const linkedIssueScript = new AsyncFunction(
  'github',
  'context',
  'core',
  extractScript(path.join(root, 'workflows/require-linked-issue.yml'), "Check this pull request's linked issues"),
);
const xcshLinkedIssueScript = new AsyncFunction(
  'github',
  'context',
  'core',
  extractScript(path.join(root, 'workflows/super-linter.yml'), "Check this pull request's linked issues"),
);
const context = { repo: { owner: 'f5-sales-demo', repo: 'example' } };
const repoIdentityKey = ['full', 'name'].join('_');
const generatedReleasePull = {
  number: 80,
  title: 'chore: bump version to v20.23.0',
  body: 'Automated release PR generated by scripts/release.ts.\n\nRelease details.',
  user: { login: 'release-automation' },
  head: {
    ref: 'release/v20.23.0',
    repo: { [repoIdentityKey]: [context.repo.owner, context.repo.repo].join('/') },
  },
};

async function testExactPullRequestQueryPasses() {
  const graphqlCalls = [];
  const info = [];
  const failures = [];
  await linkedIssueScript(
    {
      graphql: async (_query, variables) => {
        graphqlCalls.push(variables);
        return { repository: { pullRequest: { closingIssuesReferences: { nodes: [{ number: 1693 }] } } } };
      },
    },
    { ...context, payload: { pull_request: { number: 77 } } },
    {
      info: (message) => info.push(message),
      setFailed: (message) => failures.push(message),
    },
  );
  assert.deepEqual(graphqlCalls, [{ owner: 'f5-sales-demo', repo: 'example', number: 77 }]);
  assert.deepEqual(failures, []);
  assert.match(info[0], /#77 links issue #1693/);
}

async function testMissingLinkFailsWithGuidance() {
  const failures = [];
  await linkedIssueScript(
    { graphql: async () => ({ repository: { pullRequest: { closingIssuesReferences: { nodes: [] } } } }) },
    { ...context, payload: { pull_request: { number: 78 } } },
    { info: () => {}, setFailed: (message) => failures.push(message) },
  );
  assert.equal(failures.length, 1);
  assert.match(failures[0], /Closes #123/);
}

async function testGraphqlFailureFailsClosed() {
  await assert.rejects(
    linkedIssueScript(
      {
        graphql: async () => {
          throw new Error('GraphQL unavailable');
        },
      },
      { ...context, payload: { pull_request: { number: 79 } } },
      { info: () => {}, setFailed: () => {} },
    ),
    /GraphQL unavailable/,
  );
}

async function runUnlinkedRelease(pullRequest, script = linkedIssueScript, automationLogin = 'release-automation') {
  const graphqlCalls = [];
  const info = [];
  const failures = [];
  const previousLogin = process.env.RELEASE_AUTOMATION_LOGIN;
  process.env.RELEASE_AUTOMATION_LOGIN = automationLogin;
  try {
    await script(
      {
        graphql: async (_query, variables) => {
          graphqlCalls.push(variables);
          return { repository: { pullRequest: { closingIssuesReferences: { nodes: [] } } } };
        },
      },
      { ...context, payload: { pull_request: pullRequest } },
      {
        info: (message) => info.push(message),
        setFailed: (message) => failures.push(message),
      },
    );
  } finally {
    if (previousLogin === undefined) delete process.env.RELEASE_AUTOMATION_LOGIN;
    else process.env.RELEASE_AUTOMATION_LOGIN = previousLogin;
  }
  return { graphqlCalls, info, failures };
}

async function testAuthenticatedGeneratedReleasePassesWithoutIssue() {
  for (const script of [linkedIssueScript, xcshLinkedIssueScript]) {
    const result = await runUnlinkedRelease(generatedReleasePull, script);
    assert.deepEqual(result.graphqlCalls, []);
    assert.deepEqual(result.failures, []);
    assert.match(result.info[0], /authenticated generated release v20\.23\.0/);
  }
}

async function testGeneratedReleaseBoundaryFailsClosed() {
  const cases = [
    {
      name: 'human-authored release',
      pull: { ...generatedReleasePull, user: { login: 'release-manager' } },
    },
    {
      name: 'fork-authored release',
      pull: {
        ...generatedReleasePull,
        head: { ...generatedReleasePull.head, repo: { [repoIdentityKey]: ['external', context.repo.repo].join('/') } },
      },
    },
    {
      name: 'malformed release branch',
      pull: {
        ...generatedReleasePull,
        head: { ...generatedReleasePull.head, ref: 'release/v20.23' },
      },
    },
    {
      name: 'mismatched title version',
      pull: { ...generatedReleasePull, title: 'chore: bump version to v20.24.0' },
    },
    {
      name: 'non-canonical version',
      pull: {
        ...generatedReleasePull,
        title: 'chore: bump version to v020.23.0',
        head: { ...generatedReleasePull.head, ref: 'release/v020.23.0' },
      },
    },
    {
      name: 'missing generator marker',
      pull: { ...generatedReleasePull, body: 'Release details.' },
    },
  ];
  for (const { name, pull } of cases) {
    for (const script of [linkedIssueScript, xcshLinkedIssueScript]) {
      const result = await runUnlinkedRelease(pull, script);
      assert.equal(result.graphqlCalls.length, 1, name);
      assert.equal(result.failures.length, 1, name);
      assert.match(result.failures[0], /Closes #123/, name);
    }
  }
}

async function testMissingAutomationIdentityFailsClosed() {
  for (const script of [linkedIssueScript, xcshLinkedIssueScript]) {
    const result = await runUnlinkedRelease(generatedReleasePull, script, '');
    assert.equal(result.graphqlCalls.length, 1);
    assert.equal(result.failures.length, 1);
    assert.match(result.failures[0], /Closes #123/);
  }
}

await testExactPullRequestQueryPasses();
await testMissingLinkFailsWithGuidance();
await testGraphqlFailureFailsClosed();
await testAuthenticatedGeneratedReleasePassesWithoutIssue();
await testGeneratedReleaseBoundaryFailsClosed();
await testMissingAutomationIdentityFailsClosed();
console.log('PASS: linked-issue PR behavior is deterministic and fails closed');
